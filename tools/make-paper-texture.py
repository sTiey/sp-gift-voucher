"""
สร้างพื้นผิวกระดาษอาร์ตเคลือบมันสำหรับตัวใบคูปอง — paper-grain.webp
----------------------------------------------------------------------
ไท้สั่ง (2026-08-18): "เนื้อละเอียด ๆ เงา ๆ มัน ๆ กระดาษอาร์ตมัน เหมือนกระดาษการ์ด"

🔑 บทเรียนสองรอบก่อนหน้า — เขียนไว้กันทำผิดซ้ำ:
   รอบ 1  เม็ดละเอียดล้วนแต่จางมาก → **ไท้มองไม่เห็นเลย**
          เพราะเม็ดที่เล็กกว่าจุดภาพจะหายไปตอนย่อภาพ เห็นแค่ตอนซูม
   รอบ 2  แก้ด้วยการเติม "ปื้นหยาบ" ความถี่ต่ำเข้าไป → เห็นชัดขึ้นก็จริง
          แต่ไท้ตีกลับว่า **แรงเกินและผิดวัสดุ** — ปื้นหยาบ = กระดาษสา/คราฟท์
          ไม่ใช่กระดาษอาร์ตเคลือบมันที่ผิวแทบเรียบ

🔑 สิ่งที่ทำให้ "เห็นได้ทั้งที่ละเอียด" โดยไม่ต้องเติมปื้นหยาบ:
   **ทำเป็นผิวนูนที่รับแสง ไม่ใช่จุดมั่วสีอ่อน-เข้ม**
   สร้างสนามความสูงละเอียดก่อน แล้วหาความชันของผิวเทียบทิศแสง
   ผลคือทุกเม็ดได้ **ขอบสว่างกับขอบเงาจับคู่กันเสมอ** ซึ่งตาอ่านว่า "มันวาว/นูน"
   ต่างจากจุดมั่วที่ตาอ่านว่า "สัญญาณรบกวนบนจอ" — ความเข้มเท่ากันแต่คนละเรื่อง

🔑 ทำไมฝั่งสว่างต้องแรงกว่าฝั่งเงามาก:
   กระดาษเคลือบมันสะท้อนแสงเป็นประกายเล็ก ๆ ไม่ได้มีหลุมลึกให้เกิดเงา
   ให้ขาวนำดำ ≈ 2 เท่า → อ่านเป็น "เคลือบมัน" · ให้ดำนำเมื่อไหร่ = กลายเป็นกระดาษด้าน

ภาพเป็น RGBA โปร่งใส เพราะใบนี้มีสองพื้น (ครีมกับน้ำเงินเข้ม)
ถ้าใช้ภาพเทา + blend mode ผลบนพื้นเข้มจะอ่อนแรงจนก้านดูไม่มีเนื้อ
วางทับด้วยอัลฟาแทน → ได้ผลเท่ากันทั้งสองพื้น และไม่ต้องผสมโหมด (เบากว่าด้วย)

ปูซ้ำไร้รอยต่อเพราะกรองในโดเมนความถี่ + หาความชันแบบวนขอบ
"""
import numpy as np
from PIL import Image

OUT = 'D:/Gift vocher/assets/textures/'
SIZE = 192
rng = np.random.default_rng(20260819)


def band(noise, lo, hi):
    """กรองเอาเฉพาะช่วงความถี่ที่ต้องการ — ผลที่ได้เป็นคาบ จึงปูซ้ำไร้รอยต่อ"""
    f = np.fft.fft2(noise)
    fy = np.fft.fftfreq(SIZE)[:, None]
    fx = np.fft.fftfreq(SIZE)[None, :]
    r = np.sqrt(fx ** 2 + fy ** 2) * SIZE
    out = np.real(np.fft.ifft2(f * ((r >= lo) & (r <= hi))))
    return out / (np.abs(out).max() + 1e-9)


base = rng.standard_normal((SIZE, SIZE))

# สนามความสูงของผิว — ละเอียดล้วน ไม่มีปื้นหยาบ (ปื้นหยาบ = กระดาษด้าน ไม่ใช่อาร์ตมัน)
#   ชั้นแรก  = เนื้อผิวหลัก
#   ชั้นสอง  = ประกายจิ๋วซ้อนอีกที ทำให้ไม่ดูเป็นลายเดียวสม่ำเสมอเกินไป
height = 1.0 * band(base, 34, 70) + 0.5 * band(base, 74, 118)

# ความชันของผิวเทียบทิศแสง — np.roll = เลื่อนแบบวนขอบ จึงไม่ทำให้ขอบภาพเสีย
# แสงมาจากบนซ้าย ให้ตรงกับทิศเงานูนของตัวเลขทองบนใบ (--ft-bx/--ft-by ทอดลงขวาล่าง)
gx = np.roll(height, -1, axis=1) - np.roll(height, 1, axis=1)
gy = np.roll(height, -1, axis=0) - np.roll(height, 1, axis=0)
relief = 0.78 * gx + 0.62 * gy
relief /= np.abs(relief).max() + 1e-9

# ดันให้เฉพาะเม็ดที่รับแสงจริงโผล่ ที่เหลือเรียบไป — ผิวเคลือบมันส่วนใหญ่คือเรียบ
relief = np.sign(relief) * (np.abs(relief) ** 1.25)

# ⚠️ ขยับทีละ 0.01 พอ · ขาวต้องนำดำเสมอ ไม่งั้นกลายเป็นกระดาษด้าน
A_LIGHT = 0.152   # ประกายบนสันที่รับแสง
A_DARK = 0.076    # เงาอีกฝั่งของเม็ดเดียวกัน

pos = np.clip(relief, 0, 1)
neg = np.clip(-relief, 0, 1)

alpha = pos * A_LIGHT + neg * A_DARK
white = pos / (pos + neg + 1e-9)
rgb = (white * 255).astype(np.uint8)

img = np.zeros((SIZE, SIZE, 4), dtype=np.uint8)
img[..., 0] = rgb
img[..., 1] = rgb
img[..., 2] = rgb
img[..., 3] = np.clip(alpha * 255, 0, 255).astype(np.uint8)

Image.fromarray(img, 'RGBA').save(OUT + 'paper-grain.webp', lossless=True, quality=100)

# ตรวจรอยต่อ: ขอบซ้ายกับขอบขวาต้องต่างกันไม่เกินความต่างของพิกเซลข้างเคียงทั่วไป
a = img[..., 3].astype(float)
seam_x = np.abs(a[:, 0] - a[:, -1]).mean()
seam_y = np.abs(a[0, :] - a[-1, :]).mean()
normal = np.abs(np.diff(a, axis=1)).mean()
print('paper-grain.webp  seam_x=%.2f seam_y=%.2f  normal_neighbour_diff=%.2f'
      % (seam_x, seam_y, normal))
print('alpha: mean=%.1f max=%d   white_share=%.2f'
      % (a.mean(), a.max(), (pos > neg).mean()))
