"""
สร้าง "แผนที่สภาพแวดล้อม" ของห้อง สำหรับให้ผิวฟอยล์สะท้อน
----------------------------------------------------------------------
แนวคิดที่ถูกต้อง (เจ้าของงานอธิบายเอง):
  หลอดไฟบนเพดาน **อยู่นิ่ง** · การ์ดต่างหากที่พลิกไปมา
  ผิวที่ขรุขระไม่ได้สะท้อนหลอดไฟออกมาเป็น "ลูก ๆ" แต่กระจายจนเป็น
  **ประกายฝ้า ๆ ขุ่น ๆ ไม่สม่ำเสมอ** มีบางจุดสว่างจัด บางจุดมืดสนิท

วิธีทำ = เดียวกับที่เกมใช้ (environment map / matcap):
  อบภาพ "ห้อง" ไว้ล่วงหน้าเป็นภาพเดียว แล้วพอวัตถุเอียง
  ก็แค่ **เลื่อนตำแหน่งที่หยิบภาพมาใช้** — ไม่ต้องคำนวณแสงใหม่เลยสักเฟรม
  ถูกที่สุดเท่าที่จะเป็นไปได้ และให้ผลที่ดวงไฟอยู่กับที่จริง ๆ

ทำไมต้องเป็นภาพ ไม่ใช่ไล่เฉด: ไล่เฉดใน CSS สร้างได้แต่ลายที่ "เป็นระเบียบ"
ซึ่งตาอ่านออกทันทีว่าเป็นชั้น ๆ เป็นดวง ๆ · ความมั่วแบบมีโครงสร้างต้องมาจากภาพ
"""
import numpy as np
from PIL import Image

SIZE = 512
rng = np.random.default_rng(20260818)


def band(noise, lo, hi):
    """เก็บเฉพาะความถี่ในช่วงที่ต้องการ · ผลจากโดเมนความถี่เป็นคาบ = ปูซ้ำไร้รอยต่อ"""
    f = np.fft.fft2(noise)
    fy = np.fft.fftfreq(SIZE)[:, None]
    fx = np.fft.fftfreq(SIZE)[None, :]
    r = np.sqrt(fx ** 2 + fy ** 2) * SIZE
    out = np.real(np.fft.ifft2(f * ((r >= lo) & (r <= hi))))
    s = out.std()
    return out / s if s > 1e-9 else out


def norm(a):
    return (a - a.mean()) / (a.std() + 1e-9)


w = rng.normal(size=(SIZE, SIZE))

# ก้อนใหญ่ = โซนสว่าง/มืดของห้อง · ก้อนกลาง = ความมั่วของผิว · ริ้ว = รอยขัดของฟอยล์
blob = band(w, 2, 6)
mid = band(w, 8, 20)
fine = band(w, 26, 56)

# ริ้วยืดตามแนวนอน — ฟอยล์จริงมีทิศทางการขัด แสงจึงยืดเป็นเส้นไม่ใช่จุดกลม
streak = band(rng.normal(size=(SIZE, SIZE)), 6, 26)
streak = np.roll(streak, 0, axis=0)
kernel = np.ones((1, 9)) / 9.0
streak = np.real(np.fft.ifft2(np.fft.fft2(streak) * np.fft.fft2(kernel, s=(SIZE, SIZE))))
streak = norm(streak)

# ประวัติการชั่ง: ก้อนใหญ่ 1.35 = ลายพรางเป็นหย่อม ๆ ไม่ใช่ฟอยล์
# ต้องดันน้ำหนักไปทางริ้วกับเม็ดละเอียด เหลือก้อนใหญ่ไว้แค่พอมีโซนสว่าง-มืด
lum = norm(0.55 * blob + 0.9 * mid + 0.75 * streak + 0.5 * fine)

# ดันให้มี "จุดสว่างจัด" จริง ๆ ไม่ใช่เทากลาง ๆ ทั้งแผ่น — แต่ไม่ให้เป็นวงกลมคม
lum = np.tanh(lum * 0.7) * 1.05

# ⚠️ กราฟความสว่างต้อง **ไม่สมมาตร**
#    ผิวมันจริง = พื้นค่อนข้างสม่ำเสมอ + มีหย่อมสว่างจัดแทรกเป็นระยะ
#    ถ้าลดทั้งสองฝั่งเท่ากันจะได้ทองแบนจืด · ถ้าเพิ่มทั้งสองฝั่งจะได้ทองขึ้นสนิม
#    จึงให้ฝั่งสว่างเหวี่ยงแรงกว่าฝั่งมืดราว 3 เท่า
# ประวัติการชั่งน้ำหนัก (อย่าดันขึ้นอีก):
#   46 สมมาตร = ลายพราง · 27 สมมาตร = ทองขึ้นสนิม · 60/19 = ยังด่างอยู่
#   ปัญหาคือให้แผนที่ห้องเป็นตัวเอก ทั้งที่ทองในภาพอ้างอิงค่อนข้างเรียบ
#   ความ "ฝ้า ๆ รุ้ง ๆ" คือสิ่งที่เกิดตอนพลิก ไม่ใช่ลายด่างที่อยู่นิ่ง
#   แผนที่จึงต้องเป็นแค่ตัวกวนเบา ๆ ให้ไล่เฉดพื้นไม่เนียนเกินไป
base = np.clip(128 + np.where(lum > 0, lum * 26, lum * 9), 0, 255)

# ประกายรุ้ง: ให้แต่ละช่องสีหยิบความมั่วคนละจุดนิดเดียว → สีเหลื่อมกันเล็กน้อย
# ทองจึงเหลือบไปทางเขียว/ชมพูบ้างตามมุม ซึ่งคือสิ่งที่ตาเรียกว่า "รุ้ง ๆ"
sh = 3
img = np.stack([
    np.clip(base + np.roll(lum, sh, axis=1) * 5.0, 0, 255),
    base,
    np.clip(base - np.roll(lum, -sh, axis=1) * 5.4, 0, 255),
], axis=-1).astype(np.uint8)

Image.fromarray(img, mode='RGB').save(
    'D:/Gift vocher/assets/textures/foil-env.webp', format='WEBP', quality=88, method=6)

a = base.astype(int)
sx = np.abs(a[:, 0] - a[:, -1]).mean()
sy = np.abs(a[0, :] - a[-1, :]).mean()
inner = np.abs(a[:, 10] - a[:, 11]).mean()
print('seam-x %.1f | seam-y %.1f | normal-neighbour %.1f' % (sx, sy, inner))
print('mean %.1f | min %d | max %d | dark<100 %.1f%% | bright>170 %.1f%%'
      % (a.mean(), a.min(), a.max(), (a < 100).mean() * 100, (a > 170).mean() * 100))
